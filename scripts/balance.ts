// Balance simulator: N seeded headless runs per party size (all heroes AI-driven), in parallel
// worker threads. Reports win rate, how far runs get, boss time-to-kill and room clear times.
//   npm run balance -- --runs 1000 --sizes 1,2,3,4 --workers 4 [--persona storyteller]
import { Worker, isMainThread, parentPort, workerData } from "node:worker_threads";
import { availableParallelism } from "node:os";
import { mkdirSync, writeFileSync } from "node:fs";
import { runHeadless } from "../src/sim/headless";
import { ACTS } from "../src/data";

const BASE = ["fighter", "wizard", "rogue", "cleric"];

interface Job { seed: number; size: number; persona: string; maxMinutes: number }
interface Out { seed: number; size: number; victory: boolean; act: number; nodes: number; minutes: number; ttk: { boss: string; seconds: number }[]; rooms: number[]; downs: number; stalled: boolean; party: string[] }

function party(seed: number, size: number): string[] {
  return Array.from({ length: size }, (_, i) => BASE[(seed + i) % BASE.length]!);
}

function runOne(j: Job): Out {
  const classes = party(j.seed, j.size);
  const r = runHeadless(
    { seed: j.seed, persona: j.persona as "storyteller", mode: j.size === 1 ? "lone" : "coop", heroes: classes.map((cls, slot) => ({ slot, cls, ctrl: "ai" as const })) },
    { maxTicks: j.maxMinutes * 3600 },
  );
  return {
    seed: j.seed, size: j.size, victory: r.victory, act: r.act, nodes: r.nodes, minutes: r.ticks / 3600,
    ttk: r.ttk.map((t) => ({ boss: t.boss, seconds: t.ticks / 60 })), rooms: r.roomSeconds, downs: r.downs, stalled: r.stalled, party: classes,
  };
}

if (!isMainThread) {
  const jobs = workerData as Job[];
  for (const j of jobs) parentPort!.postMessage(runOne(j));
  parentPort!.postMessage(null);
} else {
  const arg = (k: string, d: string): string => {
    const i = process.argv.indexOf(`--${k}`);
    return i >= 0 ? process.argv[i + 1]! : d;
  };
  const runs = Number(arg("runs", "1000"));
  const sizes = arg("sizes", "1,2,3,4").split(",").map(Number);
  const workers = Math.max(1, Number(arg("workers", String(availableParallelism()))));
  const persona = arg("persona", "storyteller");
  const maxMinutes = Number(arg("max-minutes", "90"));
  const jobs: Job[] = [];
  for (const size of sizes) for (let i = 0; i < runs; i++) jobs.push({ seed: 1000 + i, size, persona, maxMinutes });
  const chunks: Job[][] = Array.from({ length: workers }, () => []);
  jobs.forEach((j, i) => chunks[i % workers]!.push(j));
  const results: Out[] = [];
  const t0 = Date.now();
  await Promise.all(chunks.map((chunk) => new Promise<void>((resolve, reject) => {
    const w = new Worker(new URL(import.meta.url), { workerData: chunk, execArgv: ["--import", "tsx"] });
    w.on("message", (m: Out | null) => {
      if (m === null) return resolve();
      results.push(m);
      if (results.length % 100 === 0) process.stderr.write(`  ${results.length}/${jobs.length} runs (${((Date.now() - t0) / 1000).toFixed(0)} s)\n`);
    });
    w.on("error", reject);
  })));
  const pct = (a: number[], p: number): number => {
    if (!a.length) return 0;
    const s = [...a].sort((x, y) => x - y);
    return s[Math.min(s.length - 1, Math.floor(p * s.length))]!;
  };
  const report: Record<string, unknown> = { generated: new Date().toISOString(), runs, persona, wallSeconds: (Date.now() - t0) / 1000, sizes: {} };
  const md: string[] = [
    `# Balance report`, ``, `${runs} seeded headless runs per party size, persona **${persona}**, all heroes AI-driven`,
    `(the companion AI, not humans: treat win rates as relative). Generated by \`npm run balance\` in ${((Date.now() - t0) / 60000).toFixed(1)} min on ${workers} workers.`, ``,
    `| Party | Win rate | Reached Act II / III / Finale | Median run | Median room clear | Downs/run | Stalls |`, `|---|---|---|---|---|---|---|`,
  ];
  const bossRows: string[] = [`| Party | ${ACTS.acts.map((a) => a.boss.replace(/_/g, " ")).join(" | ")} |`, `|---|${ACTS.acts.map(() => "---").join("|")}|`];
  for (const size of sizes) {
    const rs = results.filter((r) => r.size === size);
    const wins = rs.filter((r) => r.victory).length;
    const reached = (a: number): string => `${((rs.filter((r) => r.act >= a).length / rs.length) * 100).toFixed(0)}%`;
    const rooms = rs.flatMap((r) => r.rooms);
    const ttk: Record<string, { median: number; p90: number; n: number }> = {};
    for (const a of ACTS.acts) {
      const t = rs.flatMap((r) => r.ttk.filter((x) => x.boss === a.boss).map((x) => x.seconds));
      ttk[a.boss] = { median: pct(t, 0.5), p90: pct(t, 0.9), n: t.length };
    }
    const byClass: Record<string, { runs: number; wins: number }> = {};
    for (const r of rs) for (const c of new Set(r.party)) { byClass[c] ??= { runs: 0, wins: 0 }; byClass[c].runs++; if (r.victory) byClass[c].wins++; }
    (report.sizes as Record<string, unknown>)[size] = {
      runs: rs.length, winRate: wins / rs.length, reachedAct2: rs.filter((r) => r.act >= 1).length / rs.length,
      reachedAct3: rs.filter((r) => r.act >= 2).length / rs.length, reachedFinale: rs.filter((r) => r.act >= 3).length / rs.length,
      medianRunMinutes: pct(rs.map((r) => r.minutes), 0.5), roomClearSeconds: { median: pct(rooms, 0.5), p90: pct(rooms, 0.9) },
      downsPerRun: rs.reduce((t, r) => t + r.downs, 0) / rs.length, stalls: rs.filter((r) => r.stalled).length, bossTtkSeconds: ttk, byClass,
    };
    const label = size === 1 ? "1 (Lone Hero)" : String(size);
    md.push(`| ${label} | ${((wins / rs.length) * 100).toFixed(1)}% | ${reached(1)} / ${reached(2)} / ${reached(3)} | ${pct(rs.map((r) => r.minutes), 0.5).toFixed(1)} min | ${pct(rooms, 0.5).toFixed(0)} s | ${(rs.reduce((t, r) => t + r.downs, 0) / rs.length).toFixed(1)} | ${rs.filter((r) => r.stalled).length} |`);
    bossRows.push(`| ${label} | ${ACTS.acts.map((a) => { const t = ttk[a.boss]!; return t.n ? `${t.median.toFixed(0)} s (p90 ${t.p90.toFixed(0)}, n=${t.n})` : "—"; }).join(" | ")} |`);
  }
  md.push(``, `## Boss time-to-kill (median seconds of fight time)`, ``, ...bossRows, ``);
  mkdirSync("reports", { recursive: true });
  const stamp = new Date().toISOString().slice(0, 10);
  writeFileSync(`reports/balance-${persona}-${stamp}.json`, JSON.stringify({ ...report, results }, null, 1));
  writeFileSync("docs/BALANCE.md", md.join("\n") + "\n");
  console.log(md.join("\n"));
}
